def test_deferred_build_under_half_eager_baseline(tmp_path):
    """The 12-call build with deferred writes completes in under half the wall
    time of the same build writing eagerly, measured live on the same fixture
    grid (7f-E1.3; baseline recorded in the 7f-E session log ≈ 6.2 s)."""
    # Eager baseline: write after every call (pre-7f-E behaviour).
    eager_name = "bench_eager"
    t0 = time.perf_counter()
    _build_12call(
        eager_name,
        str(tmp_path / eager_name),
        FIXTURE_NLAY,
        FIXTURE_NROW,
        FIXTURE_NCOL,
        eager=True,
    )
    eager_s = time.perf_counter() - t0

    # Deferred: same 12 calls, one flush at the end.
    deferred_name = "bench_deferred"
    t0 = time.perf_counter()
    _build_12call(
        deferred_name,
        str(tmp_path / deferred_name),
        FIXTURE_NLAY,
        FIXTURE_NROW,
        FIXTURE_NCOL,
        eager=False,
    )
    deferred_s = time.perf_counter() - t0

    assert deferred_s < eager_s / 2, (
        f"Deferred build {deferred_s:.2f}s not under half the eager baseline "
        f"{eager_s:.2f}s (recorded E1.1 baseline ~6.2s)"
    )
