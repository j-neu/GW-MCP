"""7f-E tests — build-loop write cost (defer writes, flush explicitly).

E1.2: builder calls stage changes and defer the disk write; flush_model (and
      check_model / run_simulation / list_model_files) performs it.
E1.3: the deferred 12-call build completes in under half the eager build's wall
      time on the same fixture grid.

See tasks.md § 7f Tier E and
research/discovery/sessions/2026-08-17-7f-E-build-loop-cost.md.
"""

