# The "same fixture grid" used by the E1.1 benchmark and the E1.3 guard test.
FIXTURE_NLAY, FIXTURE_NROW, FIXTURE_NCOL = 5, 100, 120


def _build_12call(name: str, ws: str, nlay: int, nrow: int, ncol: int, eager: bool) -> None:
    """Representative 12-call regional build with raster-style arrays.

    ``eager=True`` flushes after every call (the pre-7f-E behaviour);
    ``eager=False`` flushes once at the end.
    """
    import numpy as np

    top = np.linspace(95.0, 100.0, nrow * ncol, dtype=float).reshape(nrow, ncol)
    botm = [top - 10.0 * (i + 1) for i in range(nlay)]
    k = np.full((nlay, nrow, ncol), 5.0)
    k33 = np.full((nlay, nrow, ncol), 0.5)

    def _call(fn) -> None:
        fn()
        if eager:
            flush_model(name)

    _call(lambda: _impl_create_model(name, ws, "METERS", "DAYS"))
    _call(lambda: _impl_set_simulation(name, 2, [1.0, 9.0], [1, 3], "moderate"))
    _call(lambda: _impl_add_dis_package(name, nlay, nrow, ncol, 250.0, 250.0, top, botm))  # type: ignore[arg-type]
    _call(lambda: _impl_add_npf_package(name, 1, k, k33, True))  # type: ignore[arg-type]
    _call(lambda: _impl_add_ic_package(name, 80.0))
    _call(lambda: _impl_add_sto_package(name, 1, 1e-5, 0.2, [0], True))
    _call(lambda: _impl_add_oc_package(name, None, None, None, None))
    chd = [[[lay, r, 0], 90.0] for lay in range(nlay) for r in range(nrow)]
    _call(lambda: _impl_add_boundary_package(name, "CHD", {"0": chd, "1": chd}, None))
    wel = [[[0, nrow // 2, ncol // 2], -1000.0]]
    _call(lambda: _impl_add_boundary_package(name, "WEL", {"0": wel, "1": wel}, None))
    riv = [[[0, nrow // 4, c], 60.0, 1e4, 50.0] for c in range(0, ncol, 10)]
    _call(lambda: _impl_add_boundary_package(name, "RIV", {"0": riv}, None))
    drn = [[[0, 3 * nrow // 4, c], 40.0, 1e4] for c in range(0, ncol, 10)]
    _call(lambda: _impl_add_boundary_package(name, "DRN", {"0": drn}, None))
    ghb = [[[lay, r, ncol - 1], 50.0, 1e4] for lay in range(nlay) for r in range(nrow)]
    _call(lambda: _impl_add_boundary_package(name, "GHB", {"0": ghb}, None))

    if not eager:
        flush_model(name)


def _snapshot_files(name: str) -> dict[str, bytes]:
    """Snapshot the workspace files, normalising flopy's generation-timestamp
    header line (the only content that legitimately differs between two
    identical builds run at different times)."""
    ws = resolve_workspace(name)
    out: dict[str, bytes] = {}
    for p in sorted(ws.iterdir()):
        if not (p.is_file() and not p.name.startswith(".")):
            continue
        text = p.read_bytes()
        if text.startswith(b"# File generated by"):
            lines = text.split(b"\n", 1)
            if len(lines) == 2:
                text = b"# header normalized\n" + lines[1]
        out[p.name] = text
    return out


