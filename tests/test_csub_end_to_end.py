"""Task 9 end-to-end: a tiny CSUB column through the whole calibration chain.

This is the integration proof that Tasks 2–8 compose. One MF6-gated test
builds a 1x1x2 CSUB model with the builder tools, runs it once to synthesise a
truth target, registers the observed subsidence via
``import_subsidence_observations`` and assembles the full PEST interface with
``setup_calibration`` targeting ``csub:packagedata`` from ``obs_source=
"derived"``. A second test (additionally gated on ``pestpp-ies``) executes the
calibration and asserts it completed with a real phi summary.

Every test here runs MF6 (the base run, and for the derived path the forward
wrapper is only generated by ``_generate_forward_wrapper`` when MF6 exists), so
every test carries ``@requires_mf6``; the IES test additionally carries
``@requires_pestpp_ies``.
"""

