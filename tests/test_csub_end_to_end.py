@requires_mf6
def test_tiny_csub_derived_setup_assembles_full_chain(tmp_path):
    """Builder → derived obs → setup_calibration(csub:packagedata) interface."""
    name = _build_tiny_csub(tmp_path, "tiny")
    observed = _run_base_and_register_observed(tmp_path, name)

    setup = _impl_setup_calibration(
        name, _csub_spec(), obs_source="derived", noptmax=2
    )
    assert "error" not in setup, setup
    assert setup["obs_source"] == "derived"
    assert setup["n_observations"] == len(observed) == 2
    # One parameter per (column x interbed): 2 columns x 2 interbeds.
    assert setup["n_adjustable_parameters"] == 4
    assert Path(setup["pst_file"]).exists()

    ws = resolve_workspace(name)
    csub_text = (ws / f"{name}.csub").read_text()
    assert "OPEN/CLOSE" in csub_text
    assert f"{name}.csub_packagedata.dat" in csub_text
    assert Path(setup["target_file"]).name == f"{name}.csub_packagedata.dat"
    assert (ws / setup["target_file"]).exists()
    assert Path(setup["template_file"]).name == f"{name}.csub_packagedata.dat.tpl"

    # Derived observations matched both observed dates against simulated time.
    report = setup["derived_observations"]["subsidence"]
    assert report["n_observations"] == 2
    assert report["n_matched"] == 2
    assert report["skipped_dates"] == []
    assert report["matching_deferred"] is False

    # Derived observations force the stdlib forward wrapper.
    assert setup["forward_wrapper"] is not None
    assert Path(setup["forward_wrapper"]).exists()


@requires_mf6
@requires_pestpp_ies
def test_tiny_csub_calibration_end_to_end(tmp_path):
    """The whole chain: build → register → setup → pestpp-ies completes."""
    name = _build_tiny_csub(tmp_path, "e2etiny")
    _run_base_and_register_observed(tmp_path, name)

    setup = _impl_setup_calibration(
        name, _csub_spec(), obs_source="derived", noptmax=2
    )
    assert "error" not in setup, setup

    out = _impl_run_pestpp_ies(
        name, setup["pst_file"], num_reals=6, num_workers=1
    )
    assert "error" not in out, out
    assert out["converged"] is True, out
    assert out["iterations"] >= 1, out
    # Meaningful phi: the final iteration's ensemble-mean (the .phi.actual.csv
    # `mean` column), not the inflated all-column sum. The synthetic residual is
    # a few percent of a sub-millimetre signal, so phi is small but positive.
    assert math.isfinite(out["final_phi_mean"])
    assert 0.0 < out["final_phi_mean"] < 1.0, out
    phi_csv = resolve_workspace(name) / (
        Path(setup["pst_file"]).stem + ".phi.actual.csv"
    )
    reported = float(pd.read_csv(phi_csv)["mean"].iloc[-1])
    assert out["final_phi_mean"] == pytest.approx(reported)


