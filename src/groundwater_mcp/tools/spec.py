def _impl_clone_model(source: str, name: str, workspace: str) -> dict:
    if len(name) > 16:
        raise ValueError(
            f"Model name '{name}' is {len(name)} characters; MODFLOW 6 caps "
            "MODELNAME at 16 characters. Use a shorter name."
        )
    src_ws = resolve_workspace(source)
    flush_model(source)
    dst = create_workspace(name, workspace or None)

    _OUTPUT_SUFFIXES = (".hds", ".cbb", ".cbc", ".lst")
    for f in src_ws.iterdir():
        if not f.is_file() or f.name.startswith("."):
            continue
        if f.suffix in _OUTPUT_SUFFIXES:
            continue
        if f.suffix == ".csv" and ("_obs.csv" in f.name or "_obs_summary" in f.name):
            continue
        shutil.copy2(f, dst / f.name)

    meta = read_meta(source)
    meta["name"] = name
    meta["cloned_from"] = source
    write_meta(name, meta)

    sim = mf6.MFSimulation.load(sim_ws=str(dst), verbosity_level=0)
    restore_oc_period_records(sim, dst)
    cache_sim(name, sim)
    return {
        "model": name,
        "workspace": str(dst),
        "cloned_from": source,
        "model_names": list(sim.model_names),
    }


def _impl_compare_scenarios(model_a: str, model_b: str) -> dict:
    import flopy.utils as fu

    from groundwater_mcp.tools.postprocess import (
        _compute_obs_fit,
        _impl_compute_water_balance,
    )

    def _last_heads(model: str) -> np.ndarray:
        ws = resolve_workspace(model)
        hds_files = list(ws.glob("*.hds"))
        if not hds_files:
            raise FileNotFoundError(f"No .hds output for model '{model}'. Run both models first.")
        hf = fu.HeadFile(str(hds_files[0]))
        kstpkper_list = hf.get_kstpkper()
        return hf.get_data(kstpkper=kstpkper_list[-1])

    heads_a = _last_heads(model_a)
    heads_b = _last_heads(model_b)
    if heads_a.shape != heads_b.shape:
        raise ValueError(
            f"Grid shapes differ ({heads_a.shape} vs {heads_b.shape}) — models are not "
            "directly comparable. Clone one from the other before comparing."
        )

    diff = heads_a - heads_b
    active = (np.abs(diff) < 1e20)
    d = diff[active]
    pcts = {p: float(np.percentile(d, p)) for p in (5, 25, 50, 75, 95)}
    flat_idx = int(np.argmax(np.abs(diff[active])))
    # Map flat index back to (layer, row, col)
    shape = diff.shape
    layer, row, col = np.unravel_index(flat_idx, shape)

    wb_a = _impl_compute_water_balance(model_a, kstpkper=None)
    wb_b = _impl_compute_water_balance(model_b, kstpkper=None)

    def _budget_deltas(wb1, wb2) -> dict:
        terms = sorted(
            set(wb1.get("inflow", {}))
            | set(wb2.get("inflow", {}))
            | set(wb1.get("outflow", {}))
            | set(wb2.get("outflow", {}))
        )
        return {
            term: {
                "inflow_delta": wb1["inflow"].get(term, 0.0) - wb2["inflow"].get(term, 0.0),
                "outflow_delta": wb1["outflow"].get(term, 0.0) - wb2["outflow"].get(term, 0.0),
            }
            for term in terms
        }

    fit_a = _compute_obs_fit(model_a)
    fit_b = _compute_obs_fit(model_b)
    obs_delta = None
    if fit_a and fit_b:
        obs_delta = {
            "rmse_delta": fit_a["rmse"] - fit_b["rmse"],
            "bias_delta": fit_a["bias"] - fit_b["bias"],
        }

    return {
        "model_a": model_a,
        "model_b": model_b,
        "difference": {
            "min": float(d.min()),
            "max": float(d.max()),
            "mean": float(d.mean()),
            "percentiles": pcts,
            "max_abs_at": {"layer": int(layer), "row": int(row), "col": int(col)},
        },
        "budget_deltas": _budget_deltas(wb_a, wb_b),
        "observation_fit_delta": obs_delta,
    }


