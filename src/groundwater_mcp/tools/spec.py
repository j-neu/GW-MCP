def _results_stale(model: str) -> bool:
    """True when the latest .hds output is older than any package input file."""
    ws = resolve_workspace(model)
    hds = list(ws.glob("*.hds"))
    if not hds:
        return False
    hds_mtime = max(p.stat().st_mtime for p in hds)
    for p in ws.iterdir():
        if p.is_file() and not p.name.startswith(".") and p.suffix in (
            ".dis", ".disv", ".npf", ".ic", ".sto", ".tdis", ".ims", ".oc",
            ".obs", ".wel", ".chd", ".riv", ".drn", ".ghb", ".rch", ".evt",
            ".sfr", ".nam",
        ):
            if p.stat().st_mtime > hds_mtime:
                return True
    return False


def _default_valued_packages(model: str) -> list[str]:
    """Packages whose key arrays are uniform (scalar, never sourced)."""
    from groundwater_mcp.utils.model_store import get_gwf

    gwf = get_gwf(model)
    meta = read_meta(model)
    provenance = meta.get("provenance", {})
    defaults: list[str] = []
    npf = gwf.get_package("npf")
    if npf is not None and "k" not in provenance:
        k = np.asarray(npf.k.array)
        if k.ndim == 0 or float(np.ptp(k)) == 0.0:
            defaults.append("npf.k (uniform/default)")
    dis = get_grid(gwf)
    if dis is not None and "top" not in provenance:
        top = np.asarray(dis.top.array)
        if top.ndim == 0 or float(np.ptp(top)) == 0.0:
            pkg_type = str(getattr(dis, "package_type", "dis")).lower()
            defaults.append(f"{pkg_type}.top (uniform/default)")
    return defaults


def _impl_describe_model(model: str) -> dict:
    summary = _impl_summarise_model(model)
    ws = resolve_workspace(model)
    meta = read_meta(model)
    provenance = meta.get("provenance", {})
    records = ledger.read_records(model)

    has_run = any(p for ext in (".hds", ".hed") for p in ws.rglob(f"*{ext}"))
    last_run = None
    for r in reversed(records):
        if r.get("tool") == "run_simulation":
            last_run = r
            break

    return {
        "model": model,
        "workspace": summary["workspace"],
        "units": meta.get("units"),
        "time_units": meta.get("time_units"),
        "grid": summary["grid"],
        "packages": summary["packages"],
        "boundary_types": summary["boundary_types"],
        "data_sources": provenance,
        "observations": summary["observations"],
        "unverified_defaults": _default_valued_packages(model),
        "has_run": has_run,
        "last_run": last_run,
        "results_stale": _results_stale(model),
        "ledger_entries": len(records),
    }


def _impl_export_model_report(model: str) -> dict:
    from groundwater_mcp.tools.postprocess import (
        _compute_obs_fit,
        _impl_compute_water_balance,
    )

    ws = resolve_workspace(model)
    desc = _impl_describe_model(model)
    lines: list[str] = []
    lines.append(f"# Model report: {model}")
    lines.append("")
    lines.append(f"- Workspace: `{desc['workspace']}`")
    lines.append(f"- Units: {desc['units']} / time {desc['time_units']}")
    lines.append(f"- Grid: {desc['grid'] or 'not set'}")
    lines.append(f"- Packages: {', '.join(desc['packages']) or 'none'}")
    lines.append(f"- Boundaries: {', '.join(desc['boundary_types']) or 'none'}")
    lines.append(f"- Has run: {desc['has_run']} — results stale: {desc['results_stale']}")
    lines.append("")

    lines.append("## Data sources")
    lines.append("")
    if desc["data_sources"]:
        lines.append("| Component | Source | Tool |")
        lines.append("|---|---|---|")
        for key, entry in desc["data_sources"].items():
            lines.append(f"| {key} | `{entry.get('source', '')}` | {entry.get('tool', '')} |")
    else:
        lines.append("None registered.")
    lines.append("")

    lines.append("## Observation fit")
    lines.append("")
    fit = _compute_obs_fit(model)
    if fit:
        lines.append(f"- n={fit['n']}, RMSE={fit['rmse']:.3g}, bias={fit['bias']:.3g}, "
                     f"MAE={fit['mae']:.3g}, R²={fit['r2'] if fit['r2'] is not None else 'n/a'}")
    else:
        lines.append("No observation targets or no run yet.")
    lines.append("")

    lines.append("## Water balance")
    lines.append("")
    wb = _impl_compute_water_balance(model, kstpkper=None)
    if isinstance(wb, dict) and not wb.get("error"):
        lines.append("| Term | Inflow | Outflow |")
        lines.append("|---|---|---|")
        for term in sorted(set(wb.get("inflow", {})) | set(wb.get("outflow", {}))):
            lines.append(
                f"| {term} | {wb['inflow'].get(term, 0.0):.6g} "
                f"| {wb['outflow'].get(term, 0.0):.6g} |"
            )
    else:
        lines.append("Not available (run the simulation first).")
    lines.append("")

    lines.append("## Plots")
    lines.append("")
    plots = sorted(p.name for p in ws.glob("*.png"))
    if plots:
        for name in plots:
            lines.append(f"- `{name}`")
    else:
        lines.append("None.")
    lines.append("")

    lines.append("## Tool-call history (provenance ledger)")
    lines.append("")
    for r in ledger.read_records(model):
        lines.append(f"- `{r['tool']}` — {r['change']}")
    lines.append("")

    report_path = ws / f"{model}_report.md"
    report_path.write_text("\n".join(lines), encoding="utf-8")
    return {
        "model": model,
        "report_file": str(report_path),
        "sections": [
            "description",
            "data_sources",
            "observation_fit",
            "water_balance",
            "plots",
            "ledger",
        ],
        "has_run": desc["has_run"],
        "results_stale": desc["results_stale"],
    }


