def register(mcp: FastMCP) -> None:
    """Register spec/scenario tools with the MCP server."""

    @mcp.tool()
    def apply_model_spec(model: str, spec: dict) -> dict:
        """Apply a declarative model spec to a model in any prior state.

        ``spec`` describes the grid, time discretisation, properties,
        storage, boundaries and output control in one dict (see tools.md
        "Model spec" section for the schema). Returns a structured diff of
        what changed (packages added/replaced/unchanged) rather than a bare
        confirmation."""
        try:
            return _impl_apply_model_spec(model, spec)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except ValueError as exc:
            return _err("INVALID_INPUT", str(exc))
        except Exception as exc:
            return _err("SPEC_APPLY_FAILED", str(exc))

    @mcp.tool()
    def export_model_spec(model: str) -> dict:
        """Emit the declarative spec for an existing or adopted model, so it
        can be inspected, diffed, and rebuilt (apply_model_spec)."""
        try:
            return _impl_export_model_spec(model)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except Exception as exc:
            return _err("SPEC_EXPORT_FAILED", str(exc))

    @mcp.tool()
    def export_reproducible_script(model: str) -> dict:
        """Emit a standalone run.py that rebuilds the model in pure flopy with
        no MCP dependency (7f-I5). Proves the MCP is not a lock-in."""
        try:
            return _impl_export_reproducible_script(model)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except Exception as exc:
            return _err("SCRIPT_EXPORT_FAILED", str(exc))

    @mcp.tool()
    def describe_model(model: str) -> dict:
        """Answer "what is this model, where did every number come from, and
        what is unverified?" from the provenance ledger + metadata: data-source
        provenance per array, defaults still in force, whether the run is
        current with the inputs."""
        try:
            return _impl_describe_model(model)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except Exception as exc:
            return _err("DESCRIBE_FAILED", str(exc))

    @mcp.tool()
    def export_model_report(model: str) -> dict:
        """Generate a Markdown report for the model: description, data-source
        provenance table, water balance, observation fit, plots, and the
        tool-call history. The record is the deliverable for consulting or
        regulatory work."""
        try:
            return _impl_export_model_report(model)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except Exception as exc:
            return _err("REPORT_FAILED", str(exc))

    @mcp.tool()
    def clone_model(source: str, name: str, workspace: str = "") -> dict:
        """Copy a model to a new registered workspace so a scenario does not
        destroy the base model. Binary outputs are not copied; run the clone
        to produce fresh outputs."""
        try:
            return _impl_clone_model(source, name, workspace)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except ValueError as exc:
            return _err("MODEL_EXISTS", str(exc), "Use a different clone name.")
        except Exception as exc:
            return _err("CLONE_FAILED", str(exc))

    @mcp.tool()
    def compare_scenarios(model_a: str, model_b: str) -> dict:
        """Compare two run models and return the differences — head-difference
        statistics (min/max/mean/percentiles + the max-difference cell),
        per-boundary budget deltas, and observation-fit deltas — not arrays."""
        try:
            return _impl_compare_scenarios(model_a, model_b)
        except KeyError as exc:
            return _err("MODEL_NOT_FOUND", str(exc), "Run create_model first.")
        except FileNotFoundError as exc:
            return _err("OUTPUT_FILE_MISSING", str(exc), "Run both models first.")
        except ValueError as exc:
            return _err("INVALID_INPUT", str(exc))
        except Exception as exc:
            return _err("COMPARE_FAILED", str(exc))
