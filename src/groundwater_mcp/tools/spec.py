"""spec module — declarative model spec, provenance, and scenarios (7f-G).

G1: apply_model_spec / export_model_spec — a single declarative dict describes
    the grid, time, properties, storage, boundaries and output control; the
    spec can be applied to a model in any prior state and diffed.
G2: describe_model / export_model_report — answers "what is this model, where
    did every number come from, and what is unverified?" from the provenance
    ledger + metadata.
G3: clone_model / compare_scenarios — scenario workflow without destroying the
    base model.
"""

