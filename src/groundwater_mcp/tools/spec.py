# ---------------------------------------------------------------------------
# Error helper
# ---------------------------------------------------------------------------


def _err(code: str, message: str, suggestion: str = "") -> dict:
    return {"error": True, "code": code, "message": message, "suggestion": suggestion}


# ---------------------------------------------------------------------------
# G1 — declarative model spec
# ---------------------------------------------------------------------------


def _impl_apply_model_spec(model: str, spec: dict) -> dict:
    result = apply_spec(model, spec)
    return {
        "model": model,
        "changed": result["changed"],
        "unchanged": result["unchanged"],
        "packages": result["packages"],
        "written": False,  # staged; flush at run/check/list/flush_model
    }


def _impl_export_model_spec(model: str) -> dict:
    return {"model": model, "spec": export_spec(model)}


