_SCRIPT_TEMPLATE = '''"""Reproducible build of model "{name}" — generated by groundwater-mcp.

Runs in a clean workspace with only flopy + MODFLOW 6 installed. Produces the
same model (and, after run_simulation, the same heads) as the MCP build.
"""

import json
from pathlib import Path

import flopy.mf6 as mf6

SPEC = {spec_literal}

OUT_DIR = Path(__file__).parent
RUN = {{"run": False}}.get("run", False)


def build():
    sim = mf6.MFSimulation(sim_name="mfsim", version="mf6", sim_ws=str(OUT_DIR))
    gwf = mf6.ModflowGwf(sim, modelname="{name}", model_nam_file="{name}.nam")

    time = SPEC["time"]
    mf6.ModflowTdis(
        sim, pname="tdis", time_units=SPEC.get("time_units", "DAYS"),
        nper=time["nper"],
        perioddata=[(time["perlen"][i], time["nstp"][i],
                     time.get("tsmult", 1.0)) for i in range(time["nper"])],
    )
    ims = mf6.ModflowIms(
        sim, pname="ims", complexity=str(time.get("ims_complexity", "moderate")).upper()
    )
    sim.register_ims_package(ims, [gwf.name])

    grid = SPEC["grid"]
    if grid["type"].upper() == "DIS":
        mf6.ModflowGwfdis(
            gwf, nlay=grid["nlay"], nrow=grid["nrow"], ncol=grid["ncol"],
            delr=grid["delr"], delc=grid["delc"], top=grid["top"], botm=grid["botm"],
        )
    else:
        mf6.ModflowGwfdisv(
            gwf, nlay=grid["nlay"], nvert=len(grid["vertices"]),
            vertices=grid["vertices"], cell2d=grid["cell2d"],
            top=grid["top"], botm=grid["botm"],
        )

    props = SPEC.get("properties", {{}}).get("npf")
    if props:
        mf6.ModflowGwfnpf(gwf, icelltype=props["icelltype"], k=props["k"],
                          k33=props.get("k33"), save_flows=bool(props.get("save_flows", True)))
    if "initial_conditions" in SPEC:
        mf6.ModflowGwfic(gwf, strt=SPEC["initial_conditions"]["strt"])
    if "storage" in SPEC:
        sto = SPEC["storage"]
        mf6.ModflowGwfsto(gwf, iconvert=sto["iconvert"], ss=sto["ss"],
                          sy=sto.get("sy"), save_flows=bool(sto.get("save_flows", True)))
    for pkg_name, spd in SPEC.get("boundaries", {{}}).items():
        cls = getattr(mf6, f"ModflowGwf{{pkg_name.lower()}}")
        cls(gwf, stress_period_data={{int(k): v for k, v in spd.items()}}, save_flows=True)
    oc = SPEC.get("output_control")
    if oc:
        mf6.ModflowGwfoc(gwf, head_filerecord=oc.get("head_file", "{name}.hds"),
                         budget_filerecord=oc.get("budget_file", "{name}.cbb"))
    else:
        mf6.ModflowGwfoc(gwf, head_filerecord="{name}.hds",
                         budget_filerecord="{name}.cbb",
                         saverecord=[("HEAD", "ALL"), ("BUDGET", "ALL")])
    sim.write_simulation(silent=True)
    return sim


if __name__ == "__main__":
    sim = build()
    if RUN:
        sim.run_simulation(silent=False)
'''


def _impl_export_reproducible_script(model: str) -> dict:
    import pprint

    spec = export_spec(model)
    spec_literal = pprint.pformat(spec, width=100, sort_dicts=False)
    ws = resolve_workspace(model)
    script = ws / "run.py"
    script.write_text(
        _SCRIPT_TEMPLATE.format(name=model, spec_literal=spec_literal),
        encoding="utf-8",
    )
    return {
        "model": model,
        "script_file": str(script),
        "note": "Pure-flopy rebuild script; run with `python run.py` in a "
        "clean workspace with flopy + MODFLOW 6 installed.",
    }


